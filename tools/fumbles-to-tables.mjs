#!/usr/bin/env node
/* fumbles-to-tables — data/fumble-pool.json -> data/fumbles.json
 *
 * The fumble counterpart of `pool-to-tables`, and deliberately much simpler, because the two
 * ladders are not the same kind of thing.
 *
 * An effect table's twelve rows are a **severity ladder**: row 12 has to be worse than row 6, so
 * placement is a rank-driven nearest fit with a drift cap. A fumble table's twenty rows are
 * **unordered peers** — a fumble never threatens mortal peril (concept doc §2), so there is no
 * ladder to calibrate and nothing for a rank to measure. The d20 picks flavour, not severity.
 *
 * So placement here is just: take everything tagged for this attack type, sort by id for
 * determinism, and lay it out. No rank, no bands, no drift.
 *
 * ── Short and long tables ───────────────────────────────────────────────────
 *
 * Fewer than twenty candidates leaves **placeholders**, not repeats. With peers, a repeat is not a
 * neutral filler: it silently doubles that outcome's odds, which is a design decision nobody made.
 * A placeholder says "this table needs six more fumbles" instead, which is the truth.
 *
 * More than twenty is reported as surplus rather than silently truncated — that means the attack
 * type has outgrown its table and wants either a prune or a wider `attackTypes` split.
 *
 * Usage:  node tools/fumbles-to-tables.mjs [--write]
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { FUMBLE_TABLES, FUMBLE_ROWS } from "../src/catalog/schema.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const POOL = path.join(ROOT, "data", "fumble-pool.json");
const OUT = path.join(ROOT, "data", "fumbles.json");

const pool = JSON.parse(fs.readFileSync(POOL, "utf8"));
const problems = [];
const surplus = {};

for (const entry of pool.entries) {
  if (!entry.id || !entry.name) problems.push(`fumble pool: an entry is missing \`id\` or \`name\``);
  for (const type of entry.attackTypes ?? []) {
    if (!FUMBLE_TABLES.includes(type)) problems.push(`fumble pool "${entry.id}": unknown attack type "${type}"`);
  }
  if (!entry.attackTypes?.length) problems.push(`fumble pool "${entry.id}": no \`attackTypes\`, so it can never be drawn`);
}

const entries = new Map();
const tables = {};

for (const type of FUMBLE_TABLES) {
  const candidates = pool.entries
    .filter((e) => e.attackTypes?.includes(type))
    .sort((a, b) => a.id.localeCompare(b.id));

  if (candidates.length > FUMBLE_ROWS) surplus[type] = candidates.length - FUMBLE_ROWS;

  const rows = [];
  for (let row = 1; row <= FUMBLE_ROWS; row++) {
    const candidate = candidates[row - 1];

    if (candidate) {
      if (!entries.has(candidate.id)) {
        entries.set(candidate.id, {
          id: candidate.id,
          name: candidate.name,
          text: candidate.text ?? null,
          ...(candidate.buffs?.length ? { buffs: candidate.buffs } : {}),
          note: candidate.note ?? null,
          ...(candidate.conditions?.length ? { conditions: candidate.conditions } : {}),
        });
      }
      rows.push({ range: [row, row], id: candidate.id });
    } else {
      const id = `todo-fumble-${type}-${String(row).padStart(2, "0")}`;
      entries.set(id, { id, name: `(unwritten — ${type} fumble ${row})`, text: null, note: null, placeholder: true });
      rows.push({ range: [row, row], id });
    }
  }

  tables[type] = rows;
}

const output = {
  // v4 when fumbles gained the mechanical channels (`damage`, `save`, `onFail`) — the generator's
  // stamp was left at 3 and `validateFumbles` warned about it for a while. v5 is `buff` -> `buffs`.
  version: 5,
  _generated: "GENERATED by tools/fumbles-to-tables.mjs from data/fumble-pool.json — do not hand-edit.",
  _shape:
    `One d${FUMBLE_ROWS} table per attack type, ${FUMBLE_ROWS} rows each, one face per row. Rows are ` +
    "UNORDERED PEERS — the die picks which fumble, not how bad it is. Entries are shared: one id " +
    "can appear in several tables.",
  entries: [...entries.values()].sort((a, b) => a.id.localeCompare(b.id)),
  tables,
};

const real = output.entries.filter((e) => !e.placeholder).length;
const slots = FUMBLE_TABLES.length * FUMBLE_ROWS;
const filled = Object.values(tables).flat().filter((r) => !entries.get(r.id)?.placeholder).length;

console.error(`pool    : ${pool.entries.length} fumbles`);
console.error(`entries : ${output.entries.length} (${real} real, ${output.entries.length - real} placeholder)`);
console.error(`slots   : ${filled} of ${slots} filled (${Math.round((filled / slots) * 100)}%)`);
for (const type of FUMBLE_TABLES) {
  const n = tables[type].filter((r) => !entries.get(r.id)?.placeholder).length;
  console.error(`  ${type.padEnd(10)} ${n}/${FUMBLE_ROWS}${surplus[type] ? `  (+${surplus[type]} surplus, not placed)` : ""}`);
}

if (problems.length) {
  console.error(`\n${problems.length} problem(s) — nothing written:`);
  for (const problem of problems) console.error(`  ! ${problem}`);
  process.exit(1);
}

if (process.argv.includes("--write")) {
  fs.writeFileSync(OUT, JSON.stringify(output, null, 2) + "\n", "utf8");
  console.error(`\nwrote ${path.relative(ROOT, OUT)}`);
} else {
  console.error("\n(dry run — pass --write to regenerate data/fumbles.json)");
}
